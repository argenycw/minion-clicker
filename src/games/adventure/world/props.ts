export function createProp(
  kind: WorldObjectKind,
  options: { id: string; x: number; y: number; scale?: number; width?: number; height?: number; flipX?: boolean; biomeId?: string; areaId?: string },
): WorldObject {
  const definition = propDefinitions[kind];
  if (!definition) throw new Error(`Unknown prop definition: ${kind}`);
  const scale = options.scale ?? 1;
  const maxHp = definition.maxHp === undefined ? undefined : Math.round(definition.maxHp * scale);
  const sprite = definition.sprite ? {
    ...definition.sprite,
    drawScale: (definition.sprite.drawScale ?? 1) * scale,
  } : undefined;
  return {
    id: options.id,
    kind,
    family: definition.family,
    x: options.x,
    y: options.y,
    width: options.width ?? definition.width * scale,
    height: options.height ?? definition.height * scale,
    rotation: 0,
    flipX: options.flipX,
    blocking: definition.blocking,
    collision: definition.collision,
    hp: maxHp,
    maxHp,
    hitPieces: definition.hitPieces,
    destroyPieces: definition.destroyPieces,
    castsShadow: definition.castsShadow,
    renderPriority: definition.renderPriority,
    biomeId: options.biomeId,
    areaId: options.areaId,
    loot: definition.loot,
    audio: definition.audio,
    sprite,
  };
}
